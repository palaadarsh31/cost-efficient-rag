"""Offline dependency-free smoke demonstration with a *test double*, not an LLM judge.

Never use the numbers from this script as real model-evaluation evidence.
"""
from __future__ import annotations
import json
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from judgepipe.client import Completion
from judgepipe.schema import load_cases
from judgepipe.runner import Runner
from judgepipe.rubric import RUBRIC


def scored():
    return {key: {'score':3, 'rationale':'Fixture score, not generated by a language model'} for key in RUBRIC}


class AlwaysFirstTestDouble:
    """Intentionally positional test double; verifies that bias is detected and neutralized."""
    def complete(self, messages):
        prompt=messages[1]['content']
        if 'Candidate A (UNTRUSTED)' in prompt or 'Candidate A: <answer_a>' in prompt:
            value={'winner':'A','rationale':'Synthetic A-position preference for testing only',
                   'unsupported_length_penalty_applied':False,
                   'scores_a':scored(),'scores_b':scored()}
        else:
            value={'scores':scored()}
        return Completion(json.dumps(value), prompt_tokens=10,completion_tokens=10,model='fixture-not-LLM')


if __name__ == '__main__':
    root=Path(__file__).resolve().parents[1]
    cases=load_cases(root/'judgepipe/data/suite.json')[:2]
    out=root/'results/problem2/offline_smoke'
    r=Runner(AlwaysFirstTestDouble(),judge_model='TEST_DOUBLE_NOT_LLM',
             generator_model='not_called',out_dir=out,backend='offline-test',repeats=2,
             include_baseline=True)
    result=r.run(cases)
    (out/'READ_THIS_FIRST.txt').write_text(
        'OFFLINE TEST DOUBLE ONLY. This intentionally biased scripted fixture is NOT an LLM. '
        'Its scores and flip rates must NOT be submitted as measured judge-bias results.\n',encoding='utf8')
    assert result['bias']['position_order_disagreement_rate_BEFORE_consensus'] == 1
    assert result['bias']['position_sensitive_decisions_after_consensus'] == 0
    print('OFFLINE SMOKE PASSED; positional bias detected, conflicting pairs set to tie.')
    print('These are not empirical LLM judge results. Artifacts:',out)
