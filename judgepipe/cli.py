"""CLI: python -m judgepipe run --suite judgepipe/data/suite.json --out results/problem2/live"""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path

from .client import ClientConfig, make_client, family
from .schema import load_cases
from .runner import Runner


def main(argv=None):
    p = argparse.ArgumentParser(description='Auditable LLM-as-judge A/B pipeline')
    subs = p.add_subparsers(dest='command', required=True)
    validate = subs.add_parser('validate', help='validate test suite; no API calls')
    validate.add_argument('--suite', default='judgepipe/data/suite.json')
    run = subs.add_parser('run', help='run real LLM evaluation')
    run.add_argument('--suite', default='judgepipe/data/suite.json')
    run.add_argument('--out', default='results/problem2/live')
    run.add_argument('--repeats', type=int, default=2)
    run.add_argument('--max-cases', type=int, default=None)
    run.add_argument('--max-judge-calls', type=int, default=500)
    run.add_argument('--generate-missing', action='store_true')
    run.add_argument('--prompt-for-key', action='store_true',
                     help='read missing API keys interactively without echoing or saving them')
    run.add_argument('--include-baseline',action='store_true',help='one less-controlled baseline comparison per case')
    run.add_argument('--allow-same-family', action='store_true', help='overrides self-enhancement family check; flagged')
    a = p.parse_args(argv)
    # Minimal .env support without requiring python-dotenv; real exported vars take precedence.
    envfile = Path('.env')
    if envfile.is_file():
        for line in envfile.read_text(encoding='utf8').splitlines():
            line = line.strip()
            if not line or line.startswith('#') or '=' not in line: continue
            key, val = line.split('=', 1)
            if key.strip().isidentifier():
                os.environ.setdefault(key.strip(), val.strip().strip('\"\''))
    cases = load_cases(a.suite)
    if a.command=='validate':
        print(json.dumps({'valid':True, 'cases':len(cases),
                          'paired':sum(c.candidate_b is not None for c in cases),
                          'gold_labeled':sum(bool(c.gold_winner) for c in cases),
                          'adversarial':sum(c.probe in ('padded','confidently_wrong') for c in cases)},indent=2))
        return 0
    if a.max_cases is not None:
        if a.max_cases < 1: p.error('--max-cases must be positive')
        cases = cases[:a.max_cases]
    j = ClientConfig.from_env('JUDGE')
    g = ClientConfig.from_env('GENERATOR')
    if a.prompt_for_key:
        from getpass import getpass
        if not j.api_key:
            j.api_key = getpass('Judge API key (hidden): ')
        if a.generate_missing and not g.api_key:
            g.api_key = getpass('Generator API key (hidden): ')
    if not j.model: p.error('Set JUDGE_MODEL and JUDGE_API_KEY / ANTHROPIC_API_KEY')
    if not g.model: p.error('Set GENERATOR_MODEL so judge/generator family comparison is auditable')
    jf, gf = family(j.model), family(g.model)
    if jf == gf or 'unknown' in (jf,gf):
        if not a.allow_same_family:
            p.error(f'Independent families not verified ({jf} vs {gf}). Select a distinct known judge family or explicitly use --allow-same-family.')
    judge = make_client(j)
    generator = make_client(g) if a.generate_missing else None
    r = Runner(judge, generator=generator, judge_model=j.model,generator_model=g.model,
               out_dir=a.out,repeats=a.repeats,backend='live',
               generate_missing=a.generate_missing,max_calls=a.max_judge_calls,
               include_baseline=a.include_baseline)
    report = r.run(cases)
    report['model_family_separation'] = {'judge_family':jf,'generator_family':gf,
                                         'families_differ_and_known':jf != gf and 'unknown' not in (jf,gf),
                                         'scope':'Configured model families only. Suite answers are prewritten and were not generated by this run unless --generate-missing was used.'}
    input_cost = float(os.getenv('JUDGE_INPUT_USD_PER_M','0'))
    output_cost = float(os.getenv('JUDGE_OUTPUT_USD_PER_M','0'))
    usage = report['audit']
    report['audit']['estimated_judge_usd'] = round(
        (usage['prompt_tokens']*input_cost + usage['completion_tokens']*output_cost)/1000000, 6)
    report['audit']['pricing_assumptions_usd_per_million_tokens'] = {
        'input':input_cost, 'output':output_cost,
        'note':'0 means rate not supplied, NOT that usage was free'}
    Path(a.out,'report.json').write_text(json.dumps(report,indent=2),encoding='utf8')
    print(json.dumps(report, indent=2))
    return 0 if report.get('run_status') == 'complete' else 1
